# General Decision mode prompts (spec section 5, mode 3).
# The question set is built at runtime because the user may edit the
# categories and the classifier instruction (spec section 5 mode 3;
# wired into the UI in plan Phase 8.3).

STATE_PREAMBLE = "The following is a document statement to classify:"

DEFAULT_CATEGORIES = ["Essential", "Useful", "Optional", "Not relevant"]
DEFAULT_INSTRUCTIONS = "Classify the statement by how necessary it is."
DEFAULT_CRITERIA = {
    "Essential": "States a hard requirement that must be met.",
    "Useful": "Adds value or context but is not mandatory.",
    "Optional": "Nice to have; can be skipped without harm.",
    "Not relevant": "Does not affect the decision at hand.",
}


def build_questions(categories=None, instructions=None, criteria_override=None):
    """Build the Tev1 questions dict for the General mode.

    categories/instructions editable at runtime (plan Phase 8.3).
    criteria_override: pass {option: description} to describe edited options.
    Criteria are attached only when they fully cover every choice — the
    probed contract serves 400 for partially matching criteria maps;
    criteria stays null (nullable) otherwise, never partially sent.
    """
    choices = [str(c).strip() for c in (categories or DEFAULT_CATEGORIES) if str(c).strip()]
    if len(choices) < 2:  # probed contract: choices must contain 2-26 candidates
        choices = list(DEFAULT_CATEGORIES)
    instructions = (instructions or "").strip() or DEFAULT_INSTRUCTIONS

    question = {"instructions": instructions, "type": "choice", "choices": choices}

    if criteria_override:
        full = {c: str(criteria_override.get(c, "").strip()) for c in choices}
        if all(full.values()):
            question["criteria"] = full
    elif set(choices) == set(DEFAULT_CATEGORIES):
        question["criteria"] = dict(DEFAULT_CRITERIA)

    return {"classification": question}


DECISION_TEMPLATE = {
    "state_preamble": STATE_PREAMBLE,
    "questions": build_questions(),
}

