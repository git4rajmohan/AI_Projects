def build_system_message(extra: str = "") -> dict[str, str]:
    """Return a system message dict for the Ollama messages list."""
    content = SYSTEM_PROMPT
    if extra:
        content = f"{content}\n\n{extra}"
    return {"role": "system", "content": content}


def format_tool_schemas_for_ollama(
    tool_definitions: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """
    Convert MCP tool definitions into Ollama function/tool format.

    MCP format: { name, description, inputSchema: { type, properties, required } }
    Ollama format: { type: "function", function: { name, description, parameters } }
    """
    result = []
    for td in tool_definitions:
        function_def: dict[str, Any] = {
            "name": td.get("name", ""),
            "description": td.get("description", ""),
            "parameters": td.get("inputSchema", {"type": "object", "properties": {}}),
        }
        result.append({"type": "function", "function": function_def})
    return result
