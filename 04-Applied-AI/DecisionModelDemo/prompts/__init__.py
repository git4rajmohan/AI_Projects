    CS_EXPLANATION = prompts_customer_support.EXPLANATION_TEMPLATE
    QA_EXPLANATION = prompts_qa.EXPLANATION_TEMPLATE
    GEN_EXPLANATION = prompts_general.EXPLANATION_TEMPLATE
    CS_DECISION = prompts_customer_support.DECISION_TEMPLATE
    QA_DECISION = prompts_qa.DECISION_TEMPLATE
    GEN_DECISION = prompts_general.DECISION_TEMPLATE

    TEMPLATE_SETS = (
        (prompts_customer_support.DECISION_TEMPLATE,
         "Customer was charged twice for the same subscription."),
        (prompts_qa.DECISION_TEMPLATE,
         "Login fails when Japanese characters are entered in the password field."),
        (prompts_general.DECISION_TEMPLATE,
         "This document section explains an important security requirement."),
    )
    REQUIRED_WORLDS = (
        "Use the decision model output as structured decision evidence.",
        "If the decision confidence is low, explicitly mention uncertainty.",
        "Do not invent decision values that were not provided by the decision model.",
        "Decision generated by Tev1",  # spec section 11/12 separation of roles
        "Explanation (generated by the LLM)",  # plan 5.3 exact role labels
    )

    for decision_template, scenario in TEMPLATE_SETS:
        request = build_decision_request(decision_template, scenario)
        assert request["state"] and scenario in request["state"]
        questions = request["questions"]
        assert isinstance(questions, dict) and questions
        for spec in questions.values():
            assert spec["instructions"].strip()
            assert spec["type"] in ("choice", "noul", "score")
            assert isinstance(spec["choices"], list) and 2 <= len(spec["choices"]) <= 26
            criteria = spec.get("criteria")
            if criteria is not None:
                assert set(criteria) == set(spec["choices"])

    summary = {
        "decision": "duplicate_charge",
        "confidence": 0.9826,
        "probabilities": [("duplicate_charge", 0.9826), ("none", 0.01)],
        "extra_answers": {"urgency": ("medium", None), "escalation": ("yes", 0.9)},
    }
    empty_summary = {
        "decision": None,
        "confidence": None,
        "probabilities": None,
        "extra_answers": None,
    }

    for combined in (CS_COMBINED, QA_COMBINED, GEN_COMBINED):
        prompt = build_combined_prompt(combined, "sample input", summary)
        for requirement in REQUIRED_WORLDS:
            assert requirement in prompt, requirement
        assert "{decision}" not in prompt and "{user_input}" not in prompt
        assert "98.3%" in prompt  # real summary value, percent-formatted
        assert "duplicate_charge: 98.26%" in prompt
        assert "Additional decisions generated by Tev1:\nurgency: medium" in prompt
        # None fields must read "not provided", never fabricated numbers
        bare = build_combined_prompt(combined, "sample input", empty_summary)
        assert "Confidence: not provided" in bare
        assert "Probabilities:\n(not provided)" in bare
        assert "{decision}" not in bare and "{confidence}" not in bare

    for explanation in (CS_EXPLANATION, QA_EXPLANATION, GEN_EXPLANATION):
        assert explanation.format(user_input="sample input")

