def autofill_criteria(choices, descriptions=None):
    """Full criteria map for a choice question — probed 2026-10-02: the contract
    REQUIRES criteria for every choice question (omitted key -> 400 "choice
    criteria must map option keys to descriptions or null"; explicit null -> 400
    "criteria must contain 2-26 candidates"). Options without a user-written
    description get a neutral tautological one: no invented meaning, just a
    valid payload."""
    given = descriptions or {}
    return {
        c: given.get(c) or f"'{c}' applies when it is the correct answer."
        for c in choices
    }


def build_decision_request(decision_template: dict, scenario: str) -> dict:
    """Assemble the {state, questions} pair for services.tev1_service.call_tev1.

    decision_template: a mode module's DECISION_TEMPLATE dict
    ({"state_preamble": str, "questions": {name: question-spec}}).
    """
    preamble = (decision_template.get("state_preamble") or "").strip()
    state = f"{preamble}\n{scenario}".strip() if preamble else scenario
    return {"state": state, "questions": decision_template["questions"]}


def build_combined_prompt(combined_template: str, user_input: str, tev1_summary: dict) -> str:
    """Fill a mode's COMBINED_TEMPLATE with real Tev1 summary values.

    tev1_summary comes from services.result_processor.summarize_tev1.
    Extra Tev1 answers (urgency, severity, ...) are appended when present.
    """
    confidence = tev1_summary.get("confidence")
    is_number = isinstance(confidence, (int, float)) and not isinstance(confidence, bool)
    rows = tev1_summary.get("probabilities") or []
    prompt = combined_template.format(
        user_input=user_input,
        decision=tev1_summary.get("decision") or "not provided",
        confidence=f"{confidence:.1%}" if is_number else "not provided",
        probabilities=(
            "\n".join(f"{label}: {pct * 100:.2f}%" for label, pct in rows)
            or "(not provided)"
        ),
    )
    extra = tev1_summary.get("extra_answers") or {}
    if extra:
        lines = "\n".join(f"{name}: {choice}" for name, (choice, _) in extra.items())
        prompt += f"\n\nAdditional decisions generated by Tev1:\n{lines}"
    return prompt


