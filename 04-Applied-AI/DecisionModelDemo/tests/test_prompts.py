# Phase 11 — Prompt template tests (plan 11.5). Pure string checks, no network.

import prompts.customer_support as cs
import prompts.general as gen
import prompts.qa as qa
from prompts import (MODE_TEMPLATES, autofill_criteria, build_combined_prompt,
                     build_decision_request)

EXPLANATIONS = (cs.EXPLANATION_TEMPLATE, qa.EXPLANATION_TEMPLATE, gen.EXPLANATION_TEMPLATE)
COMBINED = (cs.COMBINED_TEMPLATE, qa.COMBINED_TEMPLATE, gen.COMBINED_TEMPLATE)
DECISIONS = (cs.DECISION_TEMPLATE, qa.DECISION_TEMPLATE, gen.DECISION_TEMPLATE)

SUMMARY = {
    "decision": "duplicate_charge",
    "confidence": 0.9826,
    "probabilities": [("duplicate_charge", 0.9826), ("none", 0.01)],
    "extra_answers": {"urgency": ("medium", None), "escalation": ("yes", 0.9)},
}
EMPTY_SUMMARY = {"decision": None, "confidence": None, "probabilities": None,
                 "extra_answers": None}


def test_all_templates_format():
    request = build_decision_request(cs.DECISION_TEMPLATE, "sample scenario")
    assert request["state"].endswith("sample scenario")
    assert {"intent", "urgency", "escalation"} == set(request["questions"])
    plan_5d = request["questions"]["intent"]["choices"]
    assert plan_5d == ["duplicate_charge", "cancel_subscription", "card_declined", "none"]

    qa_request = build_decision_request(qa.DECISION_TEMPLATE, "scenario")
    assert {"category", "severity", "priority",
            "regression_required"} == set(qa_request["questions"])  # plan 5.2e

    gen_request = build_decision_request(gen.DECISION_TEMPLATE, "scenario")
    first = next(iter(gen_request["questions"].values()))
    assert first["choices"] == ["Essential", "Useful", "Optional", "Not relevant"]  # plan 5.2f

    for tpl in EXPLANATIONS:
        assert "{user_input}" in tpl
        assert tpl.format(user_input="sample input")


def test_combined_contains_requirement_language():
    # spec sections 12/11 wording; plan 11.5 "uncertainty + no-override language"
    for tpl in COMBINED:
        prompt = build_combined_prompt(tpl, "input", SUMMARY)
        assert "Use the decision model output as structured decision evidence." in prompt
        assert "If the decision confidence is low, explicitly mention uncertainty." in prompt
        assert "Do not invent decision values that were not provided" in prompt
        assert "Decision generated by Tev1" in prompt        # role separation (plan 5.3)
        assert "Explanation (generated by the LLM)" in prompt
        assert "{decision}" not in prompt and "{user_input}" not in prompt  # filled


def test_combined_empty_summary_not_provided():
    for tpl in COMBINED:
        prompt = build_combined_prompt(tpl, "input", EMPTY_SUMMARY)
        assert "Confidence: not provided" in prompt       # never fabricated
        assert "Probabilities:\n(not provided)" in prompt


def test_extra_answers_appended():
    prompt = build_combined_prompt(cs.COMBINED_TEMPLATE, "input", SUMMARY)
    assert "Additional decisions generated by Tev1:" in prompt
    assert "urgency: medium" in prompt and "escalation: yes" in prompt


def test_no_model_name_baked_in():
    from config.settings import OLLAMA_CLOUD_MODEL  # reads the real .env, like the app
    if not OLLAMA_CLOUD_MODEL:
        return
    everything = "\n".join(COMBINED + EXPLANATIONS
                           + tuple(repr(t) for t in DECISIONS))
    assert OLLAMA_CLOUD_MODEL not in everything


def test_mode_templates_mapping():
    assert set(MODE_TEMPLATES) == {"Customer Support", "QA / Testing", "General Decision"}
    for triple in MODE_TEMPLATES.values():
        assert len(triple) == 3


def test_autofill_criteria():
    # probed contract: choice questions REQUIRE a full criteria map for every choice
    full = autofill_criteria(["a", "b"], {"a": "because a"})
    assert full == {"a": "because a", "b": "'b' applies when it is the correct answer."}
    assert autofill_criteria(["x", "y"])["x"] == "'x' applies when it is the correct answer."
    given_none = autofill_criteria(["a", "b"], None)
    assert set(given_none) == {"a", "b"}